# Write crates/qso-graph-dxcluster-cli/src/country_file.rs from cty.dat (country-files.com): the file
# with its exact-callsign entries (=CALL) removed, every entity header, prefix and
# override kept, as one Rust string constant. Usage: strip-cty.sh <cty.dat>
set -euo pipefail
[[ $# -eq 1 && -f $1 ]] || { echo "usage: $0 <cty.dat>" >&2; exit 2; }
root=$(cd "$(dirname "$0")/.." && pwd)
out=$root/crates/qso-graph-dxcluster-cli/src/country_file.rs
version=$(grep -o '=VER[0-9]\{8\}' "$1" | head -1 | cut -c5-)
[[ -n $version ]] || { echo "$1: no =VERyyyymmdd entry" >&2; exit 1; }
body=$(LC_ALL=C awk '
  /^[^ \t]/ { print; next }
  {
    indent = $0; sub(/[^ \t].*/, "", indent)
    line = $0; sub(/^[ \t]+/, "", line)
    end = (line ~ /;[ \t]*$/)
    sub(/[ \t]*;?[ \t]*$/, "", line)
    n = split(line, items, ",")
    out = ""
    for (i = 1; i <= n; i++) if (items[i] != "" && substr(items[i], 1, 1) != "=") out = out (out == "" ? "" : ",") items[i]
    if (out != "") pending = pending (pending == "" ? indent : ",\n" indent) out
    if (end) { print pending ";"; pending = "" }
  }
' "$1")
grep -q '"#' <<<"$body" && { echo "$1: contains \"# and cannot be a raw string" >&2; exit 1; }
{
  printf '%s\n' '// SPDX-License-Identifier: MIT'
  printf '%s\n' "// Generated by scripts/strip-cty.sh from cty.dat (country-files.com), version $version, with its"
  printf '%s\n' '// exact-callsign entries removed. The country file is MIT-licensed; see NOTICE.md.'
  printf '%s\n' "/// The shipped country file's version, from its \`=VER\` entry."
  printf 'pub const VERSION: &str = "%s";\n' "$version"
  printf '%s\n' '/// The shipped country file: entity headers and prefixes only.'
  printf 'pub const COUNTRY_FILE: &str = r#"\n%s\n"#;\n' "$body"
} >"$out"
echo "wrote $out from cty.dat $version"
